using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

/// <summary>
/// 조개껍데기 모델 5종을 코드로 만들어 Assets/Models/Deco 에 .obj 로 저장한다.
/// 가리비(deco_scallop), 대합(deco_clam), 고둥(deco_spiral_shell), 모래 달러(deco_sand_dollar), 뿔고둥(deco_turret_shell).
/// 다른 장식 모델과 같은 팔레트 그림(palette.png, 34색)을 쓰고, 면마다 법선이 달라 각진 로우폴리로 보인다.
/// 모양이나 색을 바꾸고 싶으면 아래 숫자와 팔레트 번호만 고치고 메뉴를 다시 누른다.
/// 메뉴: 유리병 정원 > 조개 모델 만들기 (그 뒤에 '장식 모델 가져오기 설정'을 눌러야 재질이 붙는다)
/// </summary>
public static class ShellModelMaker
{
    private const string Folder = "Assets/Models/Deco/";
    private const int PaletteCount = 34;

    // 팔레트 번호: 2 흰색, 6 갈색, 7 연한 갈색, 17 분홍, 18 보라, 22 연보라, 23 살구, 24 주황, 25 산호, 27 모래, 30 크림, 31 연노랑
    private const int White = 2, Brown = 6, Tan = 7, Pink = 17, Purple = 18, Lavender = 22, Peach = 23, Orange = 24, Coral = 25, Sand = 27, Cream = 30, Yellow = 31;

    /// <summary>삼각형 모음. 면마다 따로 점을 두어 각진 모양이 되게 한다.</summary>
    private class Builder
    {
        public readonly List<Vector3> pos = new List<Vector3>();
        public readonly List<int> colors = new List<int>(); // 삼각형마다 하나

        /// <summary>삼각형을 더한다. inside(모델 안쪽 한 점)에서 멀어지는 쪽이 앞면이 되게 감는 방향을 맞춘다.</summary>
        public void Tri(Vector3 a, Vector3 b, Vector3 c, int color, Vector3 inside)
        {
            Vector3 n = Vector3.Cross(b - a, c - a);
            if (n.sqrMagnitude < 1e-14f) return; // 너무 작은 면(점으로 모인 곳)은 버린다
            Vector3 center = (a + b + c) / 3f;
            if (Vector3.Dot(n, center - inside) < 0f) { Vector3 t = b; b = c; c = t; }
            pos.Add(a); pos.Add(b); pos.Add(c);
            colors.Add(color);
        }

        public void Quad(Vector3 a, Vector3 b, Vector3 c, Vector3 d, int color, Vector3 inside)
        {
            Tri(a, b, c, color, inside);
            Tri(a, c, d, color, inside);
        }

        /// <summary>바닥이 y=0, 가로세로 가운데가 원점이 되게 옮겨서 .obj 로 쓴다.</summary>
        public void Write(string name, Quaternion? rotate = null)
        {
            if (rotate.HasValue)
                for (int i = 0; i < pos.Count; i++) pos[i] = rotate.Value * pos[i];
            Vector3 min = pos[0], max = pos[0];
            foreach (Vector3 p in pos) { min = Vector3.Min(min, p); max = Vector3.Max(max, p); }
            Vector3 shift = new Vector3(-(min.x + max.x) / 2f, -min.y, -(min.z + max.z) / 2f);

            var sb = new StringBuilder();
            CultureInfo ci = CultureInfo.InvariantCulture;
            sb.Append("# generated by ShellModelMaker\n");
            sb.Append("mtllib lowpoly_palette.mtl\n");
            sb.Append("o ").Append(name).Append('\n');
            for (int i = 0; i < PaletteCount; i++)
                sb.Append("vt ").Append(((i + 0.5f) / PaletteCount).ToString("0.00000", ci)).Append(" 0.50000\n");
            for (int i = 0; i < pos.Count; i++)
            {
                Vector3 p = pos[i] + shift;
                sb.Append("v ").Append(p.x.ToString("0.00000", ci)).Append(' ').Append(p.y.ToString("0.00000", ci)).Append(' ').Append(p.z.ToString("0.00000", ci)).Append('\n');
            }
            for (int t = 0; t < colors.Count; t++)
            {
                Vector3 n = Vector3.Cross(pos[t * 3 + 1] - pos[t * 3], pos[t * 3 + 2] - pos[t * 3]).normalized;
                sb.Append("vn ").Append(n.x.ToString("0.0000", ci)).Append(' ').Append(n.y.ToString("0.0000", ci)).Append(' ').Append(n.z.ToString("0.0000", ci)).Append('\n');
            }
            sb.Append("usemtl lowpoly_palette\n");
            for (int t = 0; t < colors.Count; t++)
            {
                int vt = colors[t] + 1, vn = t + 1;
                int a = t * 3 + 1;
                sb.Append("f ").Append(a).Append('/').Append(vt).Append('/').Append(vn).Append(' ')
                  .Append(a + 1).Append('/').Append(vt).Append('/').Append(vn).Append(' ')
                  .Append(a + 2).Append('/').Append(vt).Append('/').Append(vn).Append('\n');
            }
            File.WriteAllText(Folder + name + ".obj", sb.ToString(), new UTF8Encoding(false));
        }
    }

    [MenuItem("유리병 정원/조개 모델 만들기")]
    public static string Build()
    {
        Scallop();
        Clam();
        SandDollar();
        // 고둥: 통통하고 석 바퀴 반. 분홍과 크림 줄무늬, 입구는 분홍
        Spiral("deco_spiral_shell", turns: 3.2f, segPerTurn: 14, sides: 7, R0: 0.017f, rho0: 0.0125f, shrink: 0.21f, climb: 1.45f, colorA: Orange, colorB: Cream, cap: Pink, band: 4);
        // 뿔고둥: 길고 뾰족한 여섯 바퀴. 갈색과 크림 줄무늬
        Spiral("deco_turret_shell", turns: 6f, segPerTurn: 12, sides: 6, R0: 0.0125f, rho0: 0.0088f, shrink: 0.14f, climb: 1.6f, colorA: Brown, colorB: Cream, cap: Peach, band: 6, ringStripes: true);
        AssetDatabase.Refresh();
        return "조개 모델 5종을 만들었어요: " + Folder + " (이어서 '장식 모델 가져오기 설정'을 누르세요)";
    }

    // ───────── 가리비: 부채꼴에 갈비뼈 모양 골이 있다 ─────────
    private static void Scallop()
    {
        const float R = 0.031f;            // 부채 반지름
        const int rings = 4, ribs = 9, cols = ribs * 2;
        float span = 150f * Mathf.Deg2Rad; // 부채가 벌어진 각도
        var b = new Builder();

        Vector3 Top(int i, int k)
        {
            float s = i / (float)rings;
            float th = -span / 2f + span * k / cols;
            float bump = (k % 2 == 1) ? 1f : 0f; // 홀수 줄이 볼록한 골
            float y = 0.003f + 0.011f * (1f - s * s) + 0.0028f * s * bump;
            return new Vector3(R * s * Mathf.Sin(th), y, R * s * Mathf.Cos(th));
        }
        Vector3 Base(int k) { Vector3 p = Top(rings, k); return new Vector3(p.x, 0f, p.z); }

        Vector3 inside = new Vector3(0f, 0.002f, R * 0.5f);
        for (int i = 0; i < rings; i++)
        {
            for (int k = 0; k < cols; k++)
            {
                int color = i == 0 ? Cream : i == rings - 1 ? ((k / 2) % 2 == 0 ? Pink : Peach) : ((k / 2) % 2 == 0 ? Orange : Peach);
                b.Quad(Top(i, k), Top(i, k + 1), Top(i + 1, k + 1), Top(i + 1, k), color, inside);
            }
        }
        for (int k = 0; k < cols; k++)
        {
            b.Quad(Top(rings, k), Top(rings, k + 1), Base(k + 1), Base(k), Cream, inside);   // 가장자리 옆면
            b.Tri(new Vector3(0f, 0f, 0f), Base(k + 1), Base(k), Brown, inside);              // 아래
        }
        // 부채 양쪽 옆면 (꼭짓점에서 가장자리까지)
        foreach (int k in new[] { 0, cols })
            for (int i = 0; i < rings; i++)
            {
                Vector3 a = Top(i, k), c = Top(i + 1, k);
                b.Quad(a, c, new Vector3(c.x, 0f, c.z), new Vector3(a.x, 0f, a.z), Cream, inside);
            }
        // 바닥에 누운 채가 아니라, 꼭짓점(이음매)이 땅에 닿고 부채 쪽이 비스듬히 일어서게 기울인다. 골 무늬가 잘 보인다.
        b.Write("deco_scallop", Quaternion.Euler(-48f, 0f, 0f));
    }

    // ───────── 대합: 둥글납작한 반구에 나이테 줄무늬 ─────────
    private static void Clam()
    {
        const float a = 0.034f, c = 0.026f, h = 0.019f; // 가로 반지름, 세로 반지름, 높이
        const int rings = 7, sec = 14;
        var b = new Builder();

        Vector3 Pt(int i, int j)
        {
            float s = i / (float)rings, ang = Mathf.PI * 2f * j / sec;
            float y = 0.002f + h * Mathf.Pow(Mathf.Max(0f, 1f - s * s), 0.7f);
            return new Vector3(a * s * Mathf.Cos(ang), y, c * s * Mathf.Sin(ang));
        }
        Vector3 inside = new Vector3(0f, 0.002f, 0f);
        for (int i = 0; i < rings; i++)
            for (int j = 0; j < sec; j++)
            {
                int color = i == rings - 1 ? Pink : (i % 2 == 0 ? Lavender : Purple); // 나이테처럼 보라와 연보라가 번갈아, 가장자리는 분홍
                b.Quad(Pt(i, j), Pt(i, j + 1), Pt(i + 1, j + 1), Pt(i + 1, j), color, inside);
            }
        for (int j = 0; j < sec; j++)
        {
            Vector3 p = Pt(rings, j), q = Pt(rings, j + 1);
            b.Quad(p, q, new Vector3(q.x, 0f, q.z), new Vector3(p.x, 0f, p.z), White, inside);
            b.Tri(Vector3.zero, new Vector3(q.x, 0f, q.z), new Vector3(p.x, 0f, p.z), Brown, inside);
        }
        b.Write("deco_clam");
    }

    // ───────── 모래 달러: 납작한 원반에 다섯 잎 무늬 ─────────
    private static void SandDollar()
    {
        const float R = 0.031f, h = 0.007f;
        const int rings = 4, sec = 20;
        var b = new Builder();

        Vector3 Pt(int i, int j)
        {
            float s = i / (float)rings, ang = Mathf.PI * 2f * j / sec;
            float y = 0.002f + h * Mathf.Pow(Mathf.Max(0f, 1f - s * s), 0.8f);
            return new Vector3(R * s * Mathf.Cos(ang), y, R * s * Mathf.Sin(ang));
        }
        Vector3 inside = new Vector3(0f, 0.001f, 0f);
        for (int i = 0; i < rings; i++)
            for (int j = 0; j < sec; j++)
            {
                bool petal = (j % 4) < 2; // 72도(칸 4개)마다 잎 하나, 잎은 칸 2개 너비
                int color = i == 0 ? Brown : i == rings - 1 ? White : (petal ? Tan : Cream);
                b.Quad(Pt(i, j), Pt(i, j + 1), Pt(i + 1, j + 1), Pt(i + 1, j), color, inside);
            }
        for (int j = 0; j < sec; j++)
        {
            Vector3 p = Pt(rings, j), q = Pt(rings, j + 1);
            b.Quad(p, q, new Vector3(q.x, 0f, q.z), new Vector3(p.x, 0f, p.z), Cream, inside);
            b.Tri(Vector3.zero, new Vector3(q.x, 0f, q.z), new Vector3(p.x, 0f, p.z), Sand, inside);
        }
        b.Write("deco_sand_dollar");
    }

    // ───────── 고둥, 뿔고둥: 굵은 관을 나선으로 감아 올린다 ─────────
    /// <param name="turns">나선을 감는 바퀴 수</param>
    /// <param name="shrink">한 바퀴 돌 때마다 줄어드는 비율 (클수록 뾰족)</param>
    /// <param name="climb">한 바퀴에 올라가는 높이 (관 반지름의 몇 배)</param>
    /// <param name="band">줄무늬 한 칸의 길이 (조각 수)</param>
    private static void Spiral(string name, float turns, int segPerTurn, int sides, float R0, float rho0, float shrink, float climb,
                               int colorA, int colorB, int cap, int band, bool ringStripes = false)
    {
        int total = Mathf.RoundToInt(turns * segPerTurn);
        var b = new Builder();

        // 조각마다 관의 중심, 방향, 반지름을 미리 계산한다 (마지막 조각까지 total + 1개)
        var centers = new Vector3[total + 1];
        var radial = new Vector3[total + 1];
        var radius = new float[total + 1];
        float y = rho0;
        for (int idx = 0; idx <= total; idx++)
        {
            float t = idx / (float)segPerTurn;
            float shrinkFactor = Mathf.Max(0.12f, 1f - shrink * t);
            float ang = Mathf.PI * 2f * t;
            radial[idx] = new Vector3(Mathf.Cos(ang), 0f, Mathf.Sin(ang));
            radius[idx] = rho0 * shrinkFactor;
            centers[idx] = radial[idx] * (R0 * shrinkFactor) + Vector3.up * y;
            y += climb * radius[idx] / segPerTurn;
        }

        Vector3 Ring(int idx, int j)
        {
            float al = Mathf.PI * 2f * j / sides;
            return centers[idx] + radius[idx] * (Mathf.Cos(al) * radial[idx] + Mathf.Sin(al) * Vector3.up);
        }

        for (int idx = 0; idx < total; idx++)
        {
            Vector3 inside = (centers[idx] + centers[idx + 1]) * 0.5f;
            for (int j = 0; j < sides; j++)
            {
                // 줄무늬: 둘레 방향이면 관의 위쪽은 colorB, 아래쪽은 colorA (한 바퀴마다 띠가 쌓인다). 아니면 길이 방향으로 번갈아.
                int color = ringStripes ? (j < sides / 2 ? colorB : colorA) : (((idx / band) % 2 == 0) ? colorA : colorB);
                b.Quad(Ring(idx, j), Ring(idx, j + 1), Ring(idx + 1, j + 1), Ring(idx + 1, j), color, inside);
            }
        }
        // 입구(시작)와 꼭대기(끝)를 막는다
        for (int j = 0; j < sides; j++)
        {
            b.Tri(centers[0], Ring(0, j), Ring(0, j + 1), cap, centers[1]);
            b.Tri(centers[total], Ring(total, j), Ring(total, j + 1), colorA, centers[total - 1]);
        }
        b.Write(name);
    }
}
